create extension if not exists pgcrypto;

create table if not exists public.exam_results (
    id bigint generated by default as identity primary key,
    student_name text not null,
    register_number text not null,
    score integer not null default 0,
    total_questions integer not null default 60,
    percentage numeric(5,2) not null default 0,
    exam_status text not null default 'completed' check (exam_status in ('started', 'completed')),
    started_at timestamptz default now(),
    submitted_at timestamptz,
    created_at timestamptz default now()
);

create unique index if not exists exam_results_register_number_unique on public.exam_results (register_number);

create table if not exists public.mcq_questions (
    question_no integer primary key,
    question_text text not null,
    options jsonb not null,
    correct_option integer not null check (correct_option between 0 and 3),
    status text not null default 'active' check (status = 'active')
);

create table if not exists public.mcq_attempts (
    id uuid primary key default gen_random_uuid(),
    student_name text not null,
    register_number text not null,
    access_token text not null unique,
    status text not null default 'active' check (status in ('active', 'completed', 'expired')),
    started_at timestamptz not null default clock_timestamp(),
    expires_at timestamptz not null,
    submitted_at timestamptz,
    score integer,
    total_questions integer not null default 60,
    percentage numeric(5,2),
    created_at timestamptz not null default clock_timestamp()
);

create unique index if not exists mcq_attempts_register_number_unique on public.mcq_attempts (register_number);

