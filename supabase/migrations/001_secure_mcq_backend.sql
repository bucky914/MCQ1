create or replace function public.start_mcq_attempt(
    p_name text,
    p_register_number text,
    p_duration_minutes integer default 60
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_attempt public.mcq_attempts;
    v_total integer;
begin
    p_name := regexp_replace(trim(coalesce(p_name, '')), '\s+', ' ', 'g');
    p_register_number := trim(coalesce(p_register_number, ''));

    if p_name = '' or length(p_name) > 100 then
        return jsonb_build_object('ok', false, 'error', 'invalid_input');
    end if;

    if p_register_number = '' or length(p_register_number) > 50 then
        return jsonb_build_object('ok', false, 'error', 'invalid_input');
    end if;

    if p_duration_minutes < 1 or p_duration_minutes > 180 then
        return jsonb_build_object('ok', false, 'error', 'invalid_input');
    end if;

    if exists (select 1 from public.exam_results where register_number = p_register_number and exam_status = 'completed') then
        return jsonb_build_object('ok', false, 'error', 'already_submitted');
    end if;

    select count(*)::integer into v_total from public.mcq_questions where status = 'active';
    if v_total = 0 then
        return jsonb_build_object('ok', false, 'error', 'not_configured');
    end if;

    select * into v_attempt from public.mcq_attempts where register_number = p_register_number for update;
    if found then
        if v_attempt.student_name <> p_name then
            return jsonb_build_object('ok', false, 'error', 'name_mismatch');
        end if;
        return jsonb_build_object(
            'ok', true, 'attempt_id', v_attempt.id, 'token', v_attempt.access_token,
            'status', v_attempt.status, 'started_at', v_attempt.started_at, 'expires_at', v_attempt.expires_at,
            'student_name', v_attempt.student_name, 'register_number', v_attempt.register_number,
            'total_questions', v_attempt.total_questions, 'score', v_attempt.score, 'percentage', v_attempt.percentage
        );
    end if;

    insert into public.mcq_attempts (student_name, register_number, access_token, status, started_at, expires_at, total_questions)
    values (p_name, p_register_number, encode(gen_random_bytes(32), 'hex'), 'active',
            clock_timestamp(), clock_timestamp() + make_interval(mins => p_duration_minutes), v_total)
    returning * into v_attempt;

    return jsonb_build_object(
        'ok', true, 'attempt_id', v_attempt.id, 'token', v_attempt.access_token,
        'status', v_attempt.status, 'started_at', v_attempt.started_at, 'expires_at', v_attempt.expires_at,
        'student_name', v_attempt.student_name, 'register_number', v_attempt.register_number,
        'total_questions', v_attempt.total_questions
    );
exception
    when unique_violation then
        select * into v_attempt from public.mcq_attempts where register_number = p_register_number;
        if found and v_attempt.student_name = p_name then
            return jsonb_build_object(
                'ok', true, 'attempt_id', v_attempt.id, 'token', v_attempt.access_token,
                'status', v_attempt.status, 'started_at', v_attempt.started_at, 'expires_at', v_attempt.expires_at,
                'student_name', v_attempt.student_name, 'register_number', v_attempt.register_number,
                'total_questions', v_attempt.total_questions, 'score', v_attempt.score, 'percentage', v_attempt.percentage
            );
        end if;
        return jsonb_build_object('ok', false, 'error', 'name_mismatch');
end;
$$;

create or replace function public.finish_mcq_attempt(p_attempt_id uuid, p_token text, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_attempt public.mcq_attempts;
    v_score integer := 0;
    v_total integer := 0;
    v_percentage numeric(5,2) := 0;
    v_expired boolean := false;
    v_submitted_at timestamptz;
begin
    select * into v_attempt
      from public.mcq_attempts
     where id = p_attempt_id and access_token = p_token
     for update;

    if not found then
        return jsonb_build_object('ok', false, 'error', 'not_found');
    end if;

    if v_attempt.status <> 'active' then
        return jsonb_build_object('ok', true, 'status', v_attempt.status,
            'score', coalesce(v_attempt.score, 0), 'total_questions', v_attempt.total_questions,
            'percentage', coalesce(v_attempt.percentage, 0), 'student_name', v_attempt.student_name,
            'register_number', v_attempt.register_number, 'submitted_at', v_attempt.submitted_at);
    end if;

    if jsonb_typeof(p_answers) <> 'array' then
        return jsonb_build_object('ok', false, 'error', 'invalid_input');
    end if;

    v_expired := clock_timestamp() >= v_attempt.expires_at;

    select count(*)::integer into v_total from public.mcq_questions where status = 'active';

    select (count(*) filter (
        where jsonb_typeof(p_answers -> (q.question_no - 1)) = 'number'
          and (p_answers ->> (q.question_no - 1)) ~ '^[0-3]$'
          and (p_answers ->> (q.question_no - 1))::integer = q.correct_option
    ))::integer
    into v_score
    from public.mcq_questions q
    where q.status = 'active';

    if v_total > 0 then
        v_percentage := round((v_score::numeric / v_total::numeric) * 100, 2);
    end if;

    v_submitted_at := clock_timestamp();

    update public.mcq_attempts
       set status = case when v_expired then 'expired' else 'completed' end,
           submitted_at = v_submitted_at, score = v_score, total_questions = v_total, percentage = v_percentage
     where id = v_attempt.id;

    insert into public.exam_results (student_name, register_number, score, total_questions, percentage, exam_status, started_at, submitted_at)
    values (v_attempt.student_name, v_attempt.register_number, v_score, v_total, v_percentage, 'completed', v_attempt.started_at, v_submitted_at);

    return jsonb_build_object('ok', true,
        'status', case when v_expired then 'expired' else 'completed' end,
        'score', v_score, 'total_questions', v_total, 'percentage', v_percentage,
        'student_name', v_attempt.student_name, 'register_number', v_attempt.register_number,
        'submitted_at', v_submitted_at);
exception
    when unique_violation then
        select * into v_attempt from public.mcq_attempts where id = p_attempt_id;
        return jsonb_build_object('ok', true, 'status', v_attempt.status,
            'score', coalesce(v_attempt.score, 0), 'total_questions', v_attempt.total_questions,
            'percentage', coalesce(v_attempt.percentage, 0), 'student_name', v_attempt.student_name,
            'register_number', v_attempt.register_number, 'submitted_at', v_attempt.submitted_at);
end;
$$;

create or replace view public.exam_statistics as
select count(*) as total_students, coalesce(round(avg(score), 2), 0) as average_score,
       coalesce(round(avg(percentage), 2), 0) as average_percentage
from public.exam_results where exam_status = 'completed';

