revoke all on public.mcq_questions from anon, authenticated;
revoke all on public.mcq_attempts from anon, authenticated;
revoke insert, update, delete on public.exam_results from anon, authenticated;

revoke execute on function public.start_mcq_attempt(text, text, integer) from public, anon, authenticated;
revoke execute on function public.finish_mcq_attempt(uuid, text, jsonb) from public, anon, authenticated;
grant execute on function public.start_mcq_attempt(text, text, integer) to service_role;
grant execute on function public.finish_mcq_attempt(uuid, text, jsonb) to service_role;
grant select on public.exam_results to authenticated;
grant select on public.mcq_attempts to authenticated;

